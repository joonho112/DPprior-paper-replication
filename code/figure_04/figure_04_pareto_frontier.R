# PART B) Optional Benchmark (Runtime vs Calibration Accuracy)
# =============================================================================
# This section compares Stage 1 (A1) and Stage 2 (A2) calibration methods
# across different J values. Only runs if MAKE_BENCHMARK is set to TRUE.
# Uses: DPprior::DPprior_a1(), DPprior::DPprior_a2_newton()
# =============================================================================

if (isTRUE(MAKE_BENCHMARK)) {

  message("\nGenerating optional benchmark figure...")

  J_grid <- c(20, 50, 100, 200)
  mu0 <- K_target$mu_K
  var0 <- K_target$var_K

  # Timing helper: runs a function many times and returns median runtime
  time_median <- function(fun, times = 100) {
    t <- numeric(times)
    for (i in seq_len(times)) {
      t0 <- proc.time()[3]
      fun()
      t[i] <- proc.time()[3] - t0
    }
    stats::median(t)
  }

  bench <- data.frame()

  for (JJ in J_grid) {
    # Stage 1 (A1): moment approximation
    t_a1 <- time_median(
      function() DPprior::DPprior_a1(J = JJ, mu_K = mu0, var_K = var0),
      times = 500
    )
    fit_a1 <- DPprior::DPprior_a1(J = JJ, mu_K = mu0, var_K = var0)
    mom_a1 <- DPprior::exact_K_moments(J = JJ, a = fit_a1$a, b = fit_a1$b)
    resid_a1 <- sqrt((mom_a1$mean - mu0)^2 + (mom_a1$var - var0)^2)

    bench <- rbind(bench, data.frame(
      J = JJ, method = "Stage 1 (A1)", time_ms = 1000 * t_a1, residual = resid_a1
    ))

    # Stage 2 (A2): Newton refinement
    t_a2 <- time_median(
      function() DPprior::DPprior_a2_newton(J = JJ, mu_K = mu0, var_K = var0),
      times = 100
    )
    fit_a2 <- DPprior::DPprior_a2_newton(J = JJ, mu_K = mu0, var_K = var0)
    mom_a2 <- DPprior::exact_K_moments(J = JJ, a = fit_a2$a, b = fit_a2$b)
    resid_a2 <- sqrt((mom_a2$mean - mu0)^2 + (mom_a2$var - var0)^2)

    bench <- rbind(bench, data.frame(
      J = JJ, method = "Stage 2 (A2)", time_ms = 1000 * t_a2, residual = resid_a2
    ))
  }

  # Save benchmark data
  bench_csv <- file.path(DIR_RESULTS, "benchmark_data.csv")
  utils::write.csv(bench, bench_csv, row.names = FALSE)

  # Plot
  bench$method <- factor(bench$method, levels = c("Stage 1 (A1)", "Stage 2 (A2)"))

  p_bench <- ggplot(bench, aes(x = time_ms, y = residual,
                               color = method, shape = factor(J))) +
    geom_point(size = 2.5, alpha = 0.95) +
    scale_color_manual(values = c("Stage 1 (A1)" = cols$secondary,
                                  "Stage 2 (A2)" = cols$primary)) +
    scale_x_log10() +
    scale_y_log10() +
    {
      if (exists("theme_DPprior", where = asNamespace("DPprior"), mode = "function")) {
        DPprior::theme_DPprior(base_size = 9)
      } else {
        theme_minimal(base_size = 9)
      }
    } +
    theme(
      legend.position = "right",
      plot.title = element_text(size = 10, face = "bold"),
      plot.caption = element_text(size = 6.5, color = "grey40", hjust = 0)
    ) +
    labs(
      title = "Runtime vs Calibration Accuracy",
      x = "Runtime (ms, log scale)",
      y = "Moment residual (log scale)",
      color = "Method",
      shape = "J",
      caption = "Residual = sqrt((E[K]-mu)^2 + (Var(K)-sigma^2)^2)"
    )

  out_stub_bench <- file.path(DIR_FIG_SUPP, "Figure_E05_benchmark")
  save_plot_triple(p_bench, out_stub_bench, FIG_WIDTH, FIG_HEIGHT, FIG_DPI)

  message(sprintf("Benchmark saved: %s.{pdf,png,jpg}", out_stub_bench))
}


