      width = width, height = height,
      units = "in", dpi = dpi,
      device = grDevices::jpeg,
      quality = 95,
      bg = "white"
    )
  }

  invisible(list(pdf = pdf_path, png = png_path, jpg = jpg_path))
}


#' Compute Pareto-efficient points (minimize both x and y)
#'
#' Given a data frame with two numeric columns, identifies the Pareto frontier
#' by scanning for points with strictly improving y when sorted by x.
#'
#' @param df   Data frame
#' @param x    Column name for x-axis metric (to minimize)
#' @param y    Column name for y-axis metric (to minimize)
#' @param eps  Numerical tolerance for "strictly improving"
#' @return Subset of df containing only Pareto-efficient rows
pareto_frontier <- function(df, x, y, eps = 1e-12) {
  stopifnot(all(c(x, y) %in% names(df)))

  # Sort by x ascending
  o <- order(df[[x]], df[[y]])
  d <- df[o, , drop = FALSE]

  # One-pass scan: keep points with strictly improving y
  keep <- logical(nrow(d))
  y_best <- Inf
  for (i in seq_len(nrow(d))) {
    if (is.finite(d[[y]][i]) && (d[[y]][i] < y_best - eps)) {
      keep[i] <- TRUE
      y_best <- d[[y]][i]
    }
  }
  d[keep, , drop = FALSE]
}


