# Lambda grid: trade-off parameter
#   λ = 0 → weight-only (numerically unstable, omitted)
#   λ = 1 → K-only (TSMM solution)
#   Intermediate λ → Dual-Anchor solutions on the Pareto frontier
lambda_seq <- seq(0.05, 1, by = 0.05)   # 20 points


# =============================================================================
# 4) Compute Trade-off Curve via DPprior Package
# =============================================================================
# Uses the DPprior R package (https://joonho112.github.io/DPprior/):
#   - DPprior_fit():       K-only calibration (TSMM algorithm)
#   - DPprior_dual():      Dual-anchor optimization for given λ
#   - prob_w1_exceeds():   Compute P(w₁ > threshold | a, b)
#   - exact_K_moments():   Compute E[K_J] and Var(K_J) for Gamma(a,b)
#   - mean_w1():           Compute E[w₁ | a, b]
# =============================================================================

message("Computing Pareto frontier trade-off curve...")

# Step 1: K-only baseline fit (λ = 1, equivalent to TSMM)
message("  Step 1: K-only (TSMM) calibration...")
fit_K <- DPprior::DPprior_fit(
  J = J,
  mu_K = K_target$mu_K,
  var_K = K_target$var_K
)

cat(sprintf("    Gamma(%.4f, %.4f)\n", fit_K$a, fit_K$b))
cat(sprintf("    P(w1 > 0.5) = %.3f\n", DPprior::prob_w1_exceeds(0.5, fit_K$a, fit_K$b)))
cat(sprintf("    P(w1 > 0.9) = %.3f\n", DPprior::prob_w1_exceeds(0.9, fit_K$a, fit_K$b)))

# Step 2: Define w1 target for dual-anchor optimization
w1_target <- list(prob = list(threshold = w1_threshold, value = w1_constraint))

# Step 3: Sweep λ grid to build the trade-off curve
message("  Step 2: Computing dual-anchor solutions across lambda grid...")

tradeoff_list <- lapply(lambda_seq, function(lam) {

  if (lam == 1.0) {
    # Lambda = 1 is the K-only (TSMM) solution
    fit_curr <- fit_K
  } else {
    # Run dual-anchor optimization for this λ
    fit_curr <- tryCatch({
      DPprior::DPprior_dual(
        fit = fit_K,
        w1_target = w1_target,
        lambda = lam,
        loss_type = "adaptive",
        verbose = FALSE
      )
    }, error = function(e) {
      warning(sprintf("Optimization failed for lambda = %.2f: %s", lam, e$message))
      return(NULL)
    })
  }

  if (is.null(fit_curr)) return(NULL)

  # Compute metrics from the calibrated Gamma(a,b) prior
  K_mom <- DPprior::exact_K_moments(J, fit_curr$a, fit_curr$b)
  K_error <- abs(K_mom$mean - K_target$mu_K)

  # Dominance risk: P(w₁ > 0.9)
  dominance <- DPprior::prob_w1_exceeds(0.9, fit_curr$a, fit_curr$b)

  # Additional metrics for reference
  prob_w1_50 <- DPprior::prob_w1_exceeds(0.5, fit_curr$a, fit_curr$b)
  E_w1 <- DPprior::mean_w1(fit_curr$a, fit_curr$b)

  data.frame(
    lambda = lam,
    a = fit_curr$a,
    b = fit_curr$b,
    mu_K = K_mom$mean,
    var_K = K_mom$var,
    K_error = K_error,
    dominance = dominance,
    prob_w1_50 = prob_w1_50,
    E_w1 = E_w1
  )
})

# Combine results (drop any NULL entries from failed optimizations)
tradeoff <- do.call(rbind, Filter(Negate(is.null), tradeoff_list))

message(sprintf("  Generated %d valid solutions", nrow(tradeoff)))

# Verify dominance range
