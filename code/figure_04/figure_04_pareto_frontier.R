#' Save plot in PDF, PNG, and JPEG formats with cross-platform support
#'
#' Handles macOS Quartz, Linux Cairo, and falls back gracefully.
#' Prefers {ragg} for raster outputs if available.
save_plot_triple <- function(p, filename_stub, width, height, dpi) {

  # ---- PDF (Vector) ----
  pdf_path <- paste0(filename_stub, ".pdf")
  ggplot2::ggsave(
    filename = pdf_path,
    plot = p,
    width = width,
    height = height,
    units = "in",
    device = grDevices::pdf,
    useDingbats = FALSE
  )

  # ---- Raster setup ----
  has_ragg <- requireNamespace("ragg", quietly = TRUE)
  sysname <- tryCatch(Sys.info()[["sysname"]], error = function(e) NA_character_)

  # ---- PNG ----
  png_path <- paste0(filename_stub, ".png")
  if (isTRUE(has_ragg)) {
    ggplot2::ggsave(
      filename = png_path,
      plot = p,
      width = width, height = height,
      units = "in", dpi = dpi,
      device = ragg::agg_png,
      background = "white"
    )
  } else if (identical(sysname, "Darwin")) {
    ggplot2::ggsave(
      filename = png_path,
      plot = p,
      width = width, height = height,
      units = "in", dpi = dpi,
      device = grDevices::png,
      type = "quartz",
      bg = "white"
    )
  } else {
    ggplot2::ggsave(
      filename = png_path,
      plot = p,
      width = width, height = height,
      units = "in", dpi = dpi,
      device = "png",
      bg = "white"
    )
  }

  # ---- JPEG ----
  jpg_path <- paste0(filename_stub, ".jpg")
  if (isTRUE(has_ragg)) {
    ggplot2::ggsave(
      filename = jpg_path,
      plot = p,
      width = width, height = height,
      units = "in", dpi = dpi,
      device = ragg::agg_jpeg,
      background = "white"
    )
  } else if (identical(sysname, "Darwin")) {
    ggplot2::ggsave(
      filename = jpg_path,
      plot = p,
      width = width, height = height,
      units = "in", dpi = dpi,
      device = grDevices::jpeg,
      type = "quartz",
      quality = 95,
